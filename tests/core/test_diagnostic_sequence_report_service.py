import tempfile
import unittest
from pathlib import Path
from openpyxl import load_workbook

from core.services.diagnostic_sequence_report_service import (
    DiagnosticSequenceReportService,
    SEQUENCE_REPORT_HEADERS,
)


class DiagnosticSequenceReportServiceTests(unittest.TestCase):
    def test_default_output_filename(self):
        service = DiagnosticSequenceReportService()
        filename = service.fn_default_output_filename("300.BMS", "VF5NP")
        self.assertTrue(filename.startswith("EEIV_Sequence_Report_300.BMS_VF5NP_"))
        self.assertTrue(filename.endswith(".xlsx"))

    def test_export_sequence_creates_valid_workbook(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            service = DiagnosticSequenceReportService(report_dir=Path(tmpdir))
            output_file = Path(tmpdir) / "test_report.xlsx"

            steps_data = [
                {
                    "step": 1,
                    "sequence_name": "Read VIN",
                    "ecu": "BCM",
                    "request": "22 F1 90",
                    "delay_ms": 100,
                    "repeat": 1,
                    "expected": "62 F1 90",
                    "receive": "62 F1 90 01 02",
                    "result": "Passed",
                    "comment": "OK",
                },
                {
                    "step": 2,
                    "sequence_name": "Session Control",
                    "ecu": "BCM",
                    "request": "10 03",
                    "delay_ms": 200,
                    "repeat": 2,
                    "expected": "50 03",
                    "receive": "7F 10 12",
                    "result": "Failed",
                    "comment": "Subfunction not supported",
                },
            ]

            saved_path = service.export_sequence(
                sequence_name="300.BMS",
                vehicle_name="VF5NP",
                steps_data=steps_data,
                output_file=output_file,
            )

            self.assertTrue(saved_path.exists())

            wb = load_workbook(saved_path)
            ws = wb.active
            self.assertEqual(ws.title, "300.BMS")

            # Check banner
            self.assertEqual(ws["A1"].value, "Generated by V-CODE EEIV Diagnostic")

            # Check headers
            for idx, header in enumerate(SEQUENCE_REPORT_HEADERS, 1):
                self.assertEqual(ws.cell(row=2, column=idx).value, header)

            # Check row 1 data
            self.assertEqual(ws.cell(row=3, column=1).value, 1)
            self.assertEqual(ws.cell(row=3, column=2).value, "Read VIN")
            self.assertEqual(ws.cell(row=3, column=3).value, "BCM")
            self.assertEqual(ws.cell(row=3, column=4).value, "22 F1 90")
            self.assertEqual(ws.cell(row=3, column=9).value, "Passed")

            # Check row 2 data
            self.assertEqual(ws.cell(row=4, column=1).value, 2)
            self.assertEqual(ws.cell(row=4, column=9).value, "Failed")


if __name__ == "__main__":
    unittest.main()
